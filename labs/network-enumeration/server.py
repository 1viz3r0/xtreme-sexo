"""Northstar Yard: a small, read-only network-enumeration training target.

The HTTP and TCP surfaces are deliberately fixed.  They expose operational
clues and a generated export, but never execute request input or read arbitrary
paths.  ``config.json`` is generated by the lab runtime for each run.
"""

import json
import os
import socket
import threading
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import parse_qs, urlsplit


def load_config(root: Path) -> dict:
    config = json.loads((root / "config.json").read_text(encoding="utf-8"))
    flag = config.get("flag")
    if not isinstance(flag, str) or not flag.startswith("NET0ZE{") or not flag.endswith("}"):
        raise ValueError("per-run deployment config is required")
    return config


