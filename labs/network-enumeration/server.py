"""Northstar Yard: a small, read-only network-enumeration training target.

The HTTP and TCP surfaces are deliberately fixed.  They expose operational
clues and a generated export, but never execute request input or read arbitrary
paths.  ``config.json`` is generated by the lab runtime for each run.
"""

import json
import os
import socket
import threading
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import parse_qs, urlsplit


def load_config(root: Path) -> dict:
    config = json.loads((root / "config.json").read_text(encoding="utf-8"))
    flag = config.get("flag")
    if not isinstance(flag, str) or not flag.startswith("NET0ZE{") or not flag.endswith("}"):
        raise ValueError("per-run deployment config is required")
    return config


def make_handler(root: Path):
    config = load_config(root)
    export = json.dumps({"site": config.get("site", "Northstar Yard"), "flag": config["flag"]}, indent=2).encode()
    routes = {
        "/": ("text/html; charset=utf-8", b"""<!doctype html>
<html><head><title>Northstar Yard</title></head><body>
<h1>Northstar Yard telemetry</h1>
<p>Read-only equipment status for the yard coordination network.</p>
<ul><li><a href='/status'>Status board</a></li><li><a href='/api/registry'>Service registry</a></li></ul>
</body></html>"""),
        "/status": ("text/html; charset=utf-8", b"""<!doctype html>
<html><head><title>Northstar status</title></head><body>
<h1>Northstar Yard status</h1><p>Telemetry is nominal.</p>
<p>For the maintenance handoff, inspect the registry and the local service banner.</p>
</body></html>"""),
        "/robots.txt": ("text/plain; charset=utf-8", b"User-agent: *\nDisallow: /ops/\nSitemap: /api/registry\n"),
        "/api/health": ("application/json; charset=utf-8", b'{"healthy":true,"mode":"read-only"}'),
        "/api/registry": ("application/json; charset=utf-8", json.dumps({
            "application": "Northstar Yard", "release": "1.4.2",
            "services": [{"name": "yard-http", "port": 8000, "protocol": "http"},
                         {"name": "yard-console", "port": 9000, "protocol": "tcp"}],
            "operator_note": "The console banner documents the maintenance handoff route.",
        }).encode()),
        "/ops/maintenance.json": ("application/json; charset=utf-8", b'{"state":"scheduled","handoff":"night-shift","export":"/ops/maintenance/export.json"}'),
        "/ops/maintenance/export.json": ("application/json; charset=utf-8", export),
    }

    class Handler(BaseHTTPRequestHandler):
        server_version = "NorthstarHTTP/1.4"
        sys_version = ""

        def do_GET(self):
            request = urlsplit(self.path)
            if request.path == "/verify":
                supplied = parse_qs(request.query, keep_blank_values=True).get("flag", [""])[0]
                body = json.dumps({"valid": supplied == config["flag"], "message": "flag accepted" if supplied == config["flag"] else "flag rejected"}).encode()
                content_type = "application/json; charset=utf-8"
                status = 200
            else:
                content_type, body = routes.get(request.path, ("text/plain; charset=utf-8", b"Not found\n"))
                status = 200 if request.path in routes else 404
            self.send_response(status)
            self.send_header("Content-Type", content_type)
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.send_header("X-Content-Type-Options", "nosniff")
            self.send_header("Content-Security-Policy", "default-src 'none'")
            self.end_headers()
            self.wfile.write(body)

        def do_POST(self):
            self.send_error(405, "Read-only target")

        def log_message(self, *_args):
            pass

    return Handler


TCP_RESPONSES = {
    "HELP": "Commands: HELP INFO STATUS QUIT\n",
    "INFO": "Northstar Yard console; maintenance handoff is documented at /ops/maintenance.json on yard-http.\n",
    "STATUS": "yard-http:8000=ready; yard-console:9000=ready; mode=read-only\n",
    "MOTD": "Authorized training surface. No credentials or shell commands are available.\n",
}


def serve_tcp(root: Path, host: str, port: int, ready: threading.Event, stop: threading.Event):
    load_config(root)
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as listener:
        listener.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        listener.bind((host, port))
        listener.listen(8)
        listener.settimeout(0.2)
        ready.set()
        while not stop.is_set():
            try:
                connection, _ = listener.accept()
            except socket.timeout:
                continue
            with connection:
                connection.settimeout(2)
                connection.sendall(b"NORTHSTAR-YARD console/1.4\nType HELP for read-only commands.\n")
                while not stop.is_set():
                    try:
                        line = connection.recv(256)
                    except socket.timeout:
                        break
                    if not line:
                        break
                    command = line.decode("ascii", "ignore").strip().upper()
                    if command == "QUIT":
                        connection.sendall(b"Goodbye.\n")
                        break
                    connection.sendall(TCP_RESPONSES.get(command, "Unknown command. Type HELP.\n").encode())


def run():
    root = Path(__file__).resolve().parent
    host = os.environ.get("BIND_HOST", "0.0.0.0")
    http_port = int(os.environ.get("HTTP_PORT", "8000"))
    tcp_port = int(os.environ.get("TCP_PORT", "9000"))
    http = ThreadingHTTPServer((host, http_port), make_handler(root))
    stop = threading.Event()
    ready = threading.Event()
    thread = threading.Thread(target=serve_tcp, args=(root, host, tcp_port, ready, stop), daemon=True)
    thread.start()
    ready.wait(2)
    try:
        http.serve_forever()
    finally:
        stop.set()
        http.server_close()
        thread.join(timeout=2)


if __name__ == "__main__":
    run()
